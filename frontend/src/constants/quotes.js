export const getByCategory = (category) =>
  category === "all" ? quotes : quotes.filter((q) => q.category === category)

export const getByAuthor = (author) =>
  quotes.filter((q) => q.author.toLowerCase().includes(author.toLowerCase()))

export const getRandom = () => quotes[Math.floor(Math.random() * quotes.length)]

export const getRandomByCategory = (category) => {
  const pool = getByCategory(category)
  return pool[Math.floor(Math.random() * pool.length)]
}
